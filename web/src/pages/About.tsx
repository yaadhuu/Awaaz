import { useTranslation } from 'react-i18next'
import { PageHead } from '@/components/Shell'
import { useMeta } from '@/lib/useData'

/** Long-form explanation; kept in English and plain words (the summary lines are translated). */
const BODY: Record<string, string[]> = {
  method: [
    'We wrote 40 short emergency messages (floods, boats, supplies, medical help), each with known facts: a place, numbers with units, and sometimes a time. The same 40 fact sets are written in Malayalam, Hindi and English.',
    'Gnani Timbre speaks each message. Gnani Prisma writes down what it heard. A rule-based parser pulls the facts out of that text and we count how many are exactly right, with 95% Wilson intervals.',
    'Each message is then sent three ways over a simulated link: as Codec2 audio at 2400 bits a second (Tier A), as a packed transcript (Tier B), or as the facts alone (Tier C). For Tier A, Prisma listens to the audio after the link, as a stand-in for a person.',
  ],
  simulated: [
    'The link is a software model, not a radio. It has a fixed speed (2, 5 or 10 kbps) and loses packets in bursts (0 to 30%, Gilbert–Elliott model, seeded).',
    'All speech is synthetic. No real person was recorded. Radio noise beds are public domain, CC0 or CC BY, or generated by our own script.',
  ],
  cloud: [
    'Speech recognition and speech synthesis run on Gnani’s cloud. In a real flood the sender’s side would need the internet, which is exactly what may fail.',
    'For field use, recognition and the facts parser would have to run on the device, or at a relief post with a working uplink. Tier C needs only a few bytes, so it can travel over SMS, a mesh or a narrowband radio modem. This was not tested.',
  ],
  built: [
    'Built by Yadhu with Claude Code assisting. Engineering control was kept with a diary (docs/DIARY.md), a decision log (docs/DECISIONS.md), an experiment log with numbers copied from real outputs (docs/EXPERIMENTS.md), tests on the pure logic, staged gates, and a hard cap on paid API calls.',
    'Failures are kept in the record. The first audio-tier run was invalid because of a codec library bug; it was caught, fixed, tested and rerun, and the failed data is still in the repository.',
  ],
  team: ['Yadhu (yaadhuu on GitHub).'],
  licences: [
    'Code: MIT. Results and documentation: CC BY 4.0. Typefaces: SIL Open Font License. Radio beds: see the Library page for each file.',
  ],
}

export default function About() {
  const { t } = useTranslation()
  const meta = useMeta()
  return (
    <div>
      <PageHead no="9" title={t('about.title')} />
      <div className="max-w-3xl space-y-10" lang="en">
        {(['method', 'simulated', 'cloud', 'built', 'team', 'licences'] as const).map((k, i) => (
          <section key={k} aria-labelledby={`a-${k}`} className="grid gap-2 sm:grid-cols-[3rem_1fr]">
            <span className="num text-vermilion">{String(i + 1).padStart(2, '0')}</span>
            <div>
              <h2 id={`a-${k}`} className="display text-2xl">
                {t(`about.${k}`)}
              </h2>
              {BODY[k].map((p) => (
                <p key={p} className="mt-3">
                  {p}
                </p>
              ))}
            </div>
          </section>
        ))}
        {meta.data && (
          <p className="num text-sm text-muted">
            build {meta.data.built} · commit {meta.data.commit} · <a href={meta.data.repo.replace('/blob/main/', '')}>repository</a>
          </p>
        )}
      </div>
    </div>
  )
}
