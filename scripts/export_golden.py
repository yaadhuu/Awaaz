"""Export golden test data for the browser engine (Stage E1).

Reads the en/hi/ml corpus, runs Python facts.extract() and textpack.pack_facts()
on every message, writes web/src/lib/golden.gen.ts with the ground-truth facts
and packed bytes.  TypeScript golden tests import this file and check that the
TS engine produces identical output.

Only the measured languages (en, hi, ml) are included; the sample corpus is
excluded (the sample split is never mixed into the measured corpus).

Usage:
    uv run scripts/export_golden.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from tinytalk import corpus as cp
from tinytalk.facts import extract
from tinytalk.textpack import pack_facts

OUT = ROOT / "web" / "src" / "lib" / "golden.gen.ts"
CORPUS_DIR = ROOT / "data" / "corpus"
MEASURED_LANGS = ["en", "hi", "ml"]


def main() -> None:
    rows: list[dict[str, object]] = []
    mismatches: list[str] = []

    for lang in MEASURED_LANGS:
        messages = cp.load(str(CORPUS_DIR), lang)  # all splits (dev + test)

        for msg in messages:
            text: str = msg["text"]
            known_facts: dict[str, Any] = msg["facts"]

            # Run the Python extractor
            extracted = extract(text)

            # Check the extractor matches the stored facts
            stored_places = sorted(str(p) for p in known_facts["places"])
            stored_numbers = sorted(
                (int(n["value"]), str(n["unit"]))
                for n in known_facts["numbers"]
            )
            stored_times = sorted(
                (int(t["hour"]), str(t["period"]))
                for t in known_facts["times"]
            )

            extracted_places = sorted(extracted.places)
            extracted_numbers = sorted(extracted.numbers)
            extracted_times = sorted(extracted.times)
            extracted_dict = extracted.to_dict()

            if (
                extracted_places != stored_places
                or extracted_numbers != stored_numbers
                or extracted_times != stored_times
            ):
                mismatches.append(
                    f"MISMATCH {msg['id']}: stored={known_facts} extracted={extracted_dict}"
                )

            # Pack the extracted facts (using the Python extractor output)
            packed = pack_facts(extracted)
            rows.append(
                {
                    "id": msg["id"],
                    "lang": lang,
                    "text": text,
                    "facts": extracted_dict,
                    "packedHex": packed.hex(),
                }
            )

    if mismatches:
        print("GOLDEN MISMATCHES (Python extractor vs stored corpus):")
        for m in mismatches:
            print(" ", m)
        print(
            f"\n{len(mismatches)} mismatch(es) in {len(rows)} rows — "
            "these are REPORTED not hidden; fix lexicon.py or the corpus to clear them."
        )

    ts_data = json.dumps(rows, ensure_ascii=False, indent=2)

    lines = [
        "// AUTO-GENERATED by scripts/export_golden.py — DO NOT EDIT BY HAND.",
        "// Source: data/corpus/{en,hi,ml}.jsonl + tinytalk/facts.py + tinytalk/textpack.py",
        "// Re-run after any change to the corpus, facts.py or textpack.py.",
        "",
        "export interface GoldenRow {",
        "  id: string",
        "  lang: 'en' | 'hi' | 'ml'",
        "  text: string",
        "  facts: { places: string[]; numbers: { value: number; unit: string }[];"
        " times: { hour: number; period: string }[] }",
        "  packedHex: string",
        "}",
        "",
        f"export const GOLDEN: readonly GoldenRow[] = {ts_data} as const",
        "",
        f"export const GOLDEN_MISMATCHES = {len(mismatches)}",
        "",
    ]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(
        f"wrote {OUT.relative_to(ROOT)}  "
        f"({len(rows)} rows, {len(mismatches)} mismatches)"
    )


if __name__ == "__main__":
    main()
