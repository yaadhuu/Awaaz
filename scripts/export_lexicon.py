"""Export tinytalk/lexicon.py to web/src/lib/lexicon.gen.ts.

Python is the single source of truth. Run this script whenever lexicon.py changes.
The output file is committed but marked do-not-edit.

Usage:
    uv run scripts/export_lexicon.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from tinytalk.lexicon import (
    CLOCK_WORDS,
    HUNDRED,
    NUMBER_WORDS,
    PERIOD_STEMS,
    PLACES,
    UNIT_STEMS,
)

OUT = ROOT / "web" / "src" / "lib" / "lexicon.gen.ts"


def ts_const(name: str, value: object, annotation: str = "") -> str:
    ann = f": {annotation}" if annotation else ""
    return f"export const {name}{ann} = {json.dumps(value, ensure_ascii=False, indent=2)} as const"


def main() -> None:
    place_ids: list[str] = sorted(PLACES)
    unit_ids: list[str] = sorted(UNIT_STEMS)

    blocks = [
        "// AUTO-GENERATED by scripts/export_lexicon.py — DO NOT EDIT BY HAND.",
        "// Source of truth: tinytalk/lexicon.py",
        "// Re-run after any change to lexicon.py.",
        "",
        "/** Place id → language → list of recognised spellings (first is canonical). */",
        ts_const("PLACES", PLACES),
        "",
        "/** Sorted place ids; index = pack byte value. Must match Python sorted(PLACES). */",
        ts_const("PLACE_IDS", place_ids, "readonly string[]"),
        "",
        "/** Unit id → list of stem prefixes. */",
        ts_const("UNIT_STEMS", UNIT_STEMS),
        "",
        "/** Sorted unit ids; index = pack byte value. Must match Python sorted(UNIT_STEMS). */",
        ts_const("UNIT_IDS", unit_ids, "readonly string[]"),
        "",
        "/** Words that mark an hour (a digit right before one of these is a time). */",
        ts_const("CLOCK_WORDS", list(CLOCK_WORDS), "readonly string[]"),
        "",
        "/** Period (am/pm) → list of stem prefixes. */",
        ts_const("PERIOD_STEMS", PERIOD_STEMS),
        "",
        '/** Words meaning "hundred" in supported languages. */',
        ts_const("HUNDRED", HUNDRED, "readonly string[]"),
        "",
        "/** Number word → integer value (en 0-99, hi 1-99, ml 1-90). */",
        f"export const NUMBER_WORDS: Readonly<Record<string, number>> = "
        f"{json.dumps(NUMBER_WORDS, ensure_ascii=False, indent=2)}",
        "",
    ]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(blocks), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}  ({len(place_ids)} places, {len(unit_ids)} units)")


if __name__ == "__main__":
    main()
